// Dev-time-only completeness check: every language must expose every key
// English has. This runs once at module load in dev builds and
// console.errors exactly which keys are missing per language, so a gap
// is caught immediately instead of silently falling back to English.
if (import.meta.env.DEV) {
  const flattenKeys = (obj, prefix = '') =>
    Object.entries(obj).flatMap(([key, value]) => {
      const path = prefix ? `${prefix}.${key}` : key
      return value && typeof value === 'object' ? flattenKeys(value, path) : [path]
    })

  const referenceKeys = flattenKeys(translations.en)
  for (const [code, dict] of Object.entries(translations)) {
    if (code === 'en') continue
    const keys = new Set(flattenKeys(dict))
    const missing = referenceKeys.filter((k) => !keys.has(k))
    if (missing.length > 0) {
      // eslint-disable-next-line no-console
      console.error(`[i18n] "${code}" is missing ${missing.length} key(s): ${missing.join(', ')}`)
    }
  }
}
